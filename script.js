function openModal(id) {
  playClickSound();
  const w = women[id];
  if (!w) return;

  document.getElementById("modal-img").src = w.img;
  document.getElementById("modal-name").textContent = w.name;
  document.getElementById("modal-text").textContent = w.text;
  document.getElementById("modal-quote").textContent = w.quote;
  document.getElementById("modal-fact").textContent = w.fact || "";

  document.getElementById("modal-full").style.display = "none";
  document.getElementById("modal-full-text").textContent = w.full || "";
  const moreBtn = document.getElementById("more-btn");
  moreBtn.textContent = "Подробнее →";
  moreBtn.style.display = w.full ? "inline-block" : "none";

  document.getElementById("modal").style.display = "flex";
  document.body.style.overflow = "hidden";
}

function closeModal() {
  document.getElementById("modal").style.display = "none";
  document.body.style.overflow = "auto";
}


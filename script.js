function toggleRole(event) {
  event.stopPropagation();
  const roleEl = event.currentTarget;
  const tip = roleEl.parentElement.querySelector(".role-tip");

  document.querySelectorAll(".role-tip.show").forEach(t => {
    if (t !== tip) t.classList.remove("show");
  });

  tip.classList.toggle("show");
}

